// Lock pins every git source to a commit. It lives next to skills.yaml.
type Lock struct {
	Sources map[string]LockEntry `yaml:"sources"`
}

type LockEntry struct {
	Git    string `yaml:"git"`
	Ref    string `yaml:"ref,omitempty"`
	Commit string `yaml:"commit"`
}

func LoadLock(path string) (*Lock, error) {
	lock := &Lock{Sources: map[string]LockEntry{}}
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return lock, nil
	}
	if err != nil {
		return nil, err
	}
	if err := yaml.Unmarshal(data, lock); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if lock.Sources == nil {
		lock.Sources = map[string]LockEntry{}
	}
	return lock, nil
}

func (l *Lock) Save(path string) error {
	var buf bytes.Buffer
	buf.WriteString("# Generated by skillex. Run `skillex update` to move a source forward.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(l); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	return writeFileAtomic(path, buf.Bytes())
}

// Skill is one directory with a SKILL.md inside a source.
type Skill struct {
	Source      string
	ID          string // directory relative to the source root, "/"-separated
	Name        string // link name, from frontmatter or directory name
	Description string
	Dir         string
}

// ResolvedSource is a source that is present on disk at a known version.
type ResolvedSource struct {
	*Source
	Root    string // directory that is scanned and linked from
	Missing bool   // optional local source that does not exist on this host
	Commit  string // git sources only
	Skills  []Skill
}

type resolveMode int

const (
	// resolveLocked checks out the locked commit and fetches only when needed.
	resolveLocked resolveMode = iota
	// resolveUpdate fetches the configured ref and moves the lock to it.
	resolveUpdate
)

func cacheDir() (string, error) {
	base := os.Getenv("XDG_DATA_HOME")
	if base == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			return "", err
		}
		base = filepath.Join(home, ".local", "share")
	}
	return filepath.Join(base, "skillex", "repos"), nil
}

// ResolveSources makes every source available on disk and scans its skills.
// Sources named in update are moved to their latest ref; all others stay locked.
func ResolveSources(cfg *Config, lock *Lock, update map[string]bool, log func(string, ...any)) ([]ResolvedSource, bool, error) {
	cache, err := cacheDir()
	if err != nil {
		return nil, false, err
	}
	lockChanged := false
	var out []ResolvedSource
	for i := range cfg.Sources {
		src := &cfg.Sources[i]
		rs := ResolvedSource{Source: src}
		if src.IsGit() {
			rs.Root = filepath.Join(cache, src.Name)
			mode := resolveLocked
			if update[src.Name] {
				mode = resolveUpdate
			}
			commit, changed, err := syncRepo(src, rs.Root, lock, mode, log)
			if err != nil {
				return nil, false, fmt.Errorf("source %s: %w", src.Name, err)
			}
			rs.Commit = commit
			lockChanged = lockChanged || changed
		} else {
			rs.Root = cfg.Resolve(src.Path)
			if fi, err := os.Stat(rs.Root); err != nil || !fi.IsDir() {
				if !src.Optional {
					return nil, false, fmt.Errorf("source %s: %s is not a directory", src.Name, rs.Root)
				}
				rs.Missing = true
				out = append(out, rs)
				continue
			}
		}
		skills, err := scanSkills(src.Name, rs.Root)
		if err != nil {
			return nil, false, fmt.Errorf("source %s: %w", src.Name, err)
		}
		rs.Skills = skills
		out = append(out, rs)
	}
	return out, lockChanged, nil
}

func syncRepo(src *Source, dir string, lock *Lock, mode resolveMode, log func(string, ...any)) (string, bool, error) {
	if _, err := os.Stat(filepath.Join(dir, ".git")); err != nil {
		log("cloning %s", src.Git)
		if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
			return "", false, err
		}
		if _, err := git("", "clone", "--quiet", src.Git, dir); err != nil {
			return "", false, err
		}
	} else if url, _ := git(dir, "remote", "get-url", "origin"); url != src.Git {
		if _, err := git(dir, "remote", "set-url", "origin", src.Git); err != nil {
			return "", false, err
		}
	}

	ref := src.Ref
	if ref == "" {
		ref = "HEAD"
	}
	entry, locked := lock.Sources[src.Name]
	locked = locked && entry.Git == src.Git && entry.Ref == src.Ref && entry.Commit != ""

	var commit string
	if mode == resolveLocked && locked {
		commit = entry.Commit
		if !hasCommit(dir, commit) {
			log("fetching %s for locked commit %s", src.Name, short(commit))
			if _, err := git(dir, "fetch", "--quiet", "origin", ref); err != nil {
				return "", false, err
			}
			if !hasCommit(dir, commit) {
				if _, err := git(dir, "fetch", "--quiet", "origin", commit); err != nil {
					return "", false, fmt.Errorf("locked commit %s not available: %w", commit, err)
				}
			}
		}
	} else {
		log("fetching %s (%s)", src.Name, ref)
		if _, err := git(dir, "fetch", "--quiet", "origin", ref); err != nil {
			return "", false, err
		}
		var err error
		if commit, err = git(dir, "rev-parse", "FETCH_HEAD^{commit}"); err != nil {
			return "", false, err
		}
	}

	head, _ := git(dir, "rev-parse", "HEAD")
	if head != commit {
		if _, err := git(dir, "-c", "advice.detachedHead=false", "checkout", "--quiet", "--force", "--detach", commit); err != nil {
			return "", false, err
		}
	}
	newEntry := LockEntry{Git: src.Git, Ref: src.Ref, Commit: commit}
	changed := lock.Sources[src.Name] != newEntry
	lock.Sources[src.Name] = newEntry
	return commit, changed, nil
}

func hasCommit(dir, commit string) bool {
	_, err := git(dir, "cat-file", "-e", commit+"^{commit}")
	return err == nil
}

func git(dir string, args ...string) (string, error) {
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_TERMINAL_PROMPT=0")
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(stderr.String())
		if msg == "" {
			msg = err.Error()
		}
		return "", fmt.Errorf("git %s: %s", strings.Join(args, " "), msg)
	}
	return strings.TrimSpace(stdout.String()), nil
}

func short(commit string) string {
	if len(commit) > 10 {
		return commit[:10]
	}
	return commit
}

var skipDirs = map[string]bool{"node_modules": true, "vendor": true}

// scanSkills finds every directory with a SKILL.md below root. A skill's own
// subdirectories are not searched; hidden directories are skipped.
func scanSkills(source, root string) ([]Skill, error) {
	var skills []Skill
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		if path != root && (strings.HasPrefix(d.Name(), ".") || skipDirs[d.Name()]) {
			return filepath.SkipDir
		}
		manifest := filepath.Join(path, "SKILL.md")
		if fi, err := os.Stat(manifest); err != nil || !fi.Mode().IsRegular() {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		sk := Skill{Source: source, ID: filepath.ToSlash(rel), Name: filepath.Base(path), Dir: path}
		if fm := readFrontmatter(manifest); fm.Name != "" && !strings.ContainsAny(fm.Name, `/\`) {
			sk.Name = fm.Name
			sk.Description = fm.Description
		} else {
			sk.Description = fm.Description
		}
		skills = append(skills, sk)
		return filepath.SkipDir
	})
	sort.Slice(skills, func(i, j int) bool { return skills[i].ID < skills[j].ID })
	return skills, err
}

type frontmatter struct {
	Name        string `yaml:"name"`
	Description string `yaml:"description"`
}

func readFrontmatter(path string) frontmatter {
	var fm frontmatter
	data, err := os.ReadFile(path)
	if err != nil {
		return fm
	}
	text := strings.ReplaceAll(strings.TrimPrefix(string(data), "\uFEFF"), "\r\n", "\n")
	if !strings.HasPrefix(text, "---\n") {
		return fm
	}
	end := strings.Index(text[4:], "\n---")
	if end < 0 {
		return fm
	}
	_ = yaml.Unmarshal([]byte(text[4:4+end]), &fm)
	fm.Name = strings.TrimSpace(fm.Name)
	fm.Description = strings.Join(strings.Fields(fm.Description), " ")
	return fm
}
